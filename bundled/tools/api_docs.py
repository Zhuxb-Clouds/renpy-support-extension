"""Hover documentation for Ren'Py engine APIs.

Backed by ``renpy_api_docs.json``, generated by ``scripts/fetch_api.py``
from the official documentation sources.  The file is optional: when it is
missing the lookups simply return ``None`` and hover behaves as before.
"""

from __future__ import annotations

import json
import os
from typing import Dict, Optional

_DOCS: Optional[Dict[str, dict]] = None


def _load() -> Dict[str, dict]:
    global _DOCS
    if _DOCS is None:
        path = os.path.join(
            os.path.dirname(os.path.abspath(__file__)), "renpy_api_docs.json"
        )
        try:
            with open(path, encoding="utf-8") as f:
                _DOCS = json.load(f).get("entries", {})
        except (OSError, ValueError):
            _DOCS = {}
    return _DOCS


def lookup(name: str) -> Optional[dict]:
    """Documentation entry for a dotted API name (``config.screen_width``,
    ``kerning``, ``gui.text_size`` …), or ``None``."""
    return _load().get(name) or None


def hover_markdown(name: str) -> Optional[str]:
    """Markdown hover body for *name*, or ``None`` when undocumented."""
    entry = lookup(name)
    if entry is None:
        return None
    kind = entry.get("kind", "")
    signature = (entry.get("signature") or "").strip()
    if kind in ("function", "class") and signature.startswith("("):
        head = f"**{name}**{signature}"
    elif signature.startswith("="):
        head = f"**{name}** {signature}"
    elif signature:
        head = f"**{name}** *{signature}*"
    else:
        head = f"**{name}**"

    parts = [head]
    if entry.get("desc"):
        parts.append(entry["desc"])
    if entry.get("file"):
        parts.append(
            f"[📖 Ren'Py Docs](https://www.renpy.org/doc/html/{entry['file']}.html)"
        )
    return "\n\n".join(parts)
